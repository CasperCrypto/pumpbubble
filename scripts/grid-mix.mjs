/* ==========================================================================
   Builds src/gridmix.mjs — how clean each country's electricity is.

       node scripts/grid-mix.mjs          # prints
       node scripts/grid-mix.mjs --write

   Two numbers per country, the latest year each has: the lifecycle carbon
   intensity of generation (g CO2e per kWh) and the share from low-carbon
   sources (renewables and nuclear). Ember's data as Our World in Data
   publishes it (CC BY 4.0), keyed by ISO alpha-3 and turned into alpha-2 with
   the i18n-iso-countries code table (MIT). Aggregates (regions, income
   groups) carry no ISO code and are dropped.
   ========================================================================== */

import { writeFileSync } from 'node:fs';

const OUT = new URL('../src/gridmix.mjs', import.meta.url);
const UA = { 'user-agent': 'Mozilla/5.0 pumpbubble.fun/1.0 (grid-mix)' };
const CI = 'https://ourworldindata.org/grapher/carbon-intensity-electricity.csv?v=1&csvType=full&useColumnShortNames=true';
const LC = 'https://ourworldindata.org/grapher/share-electricity-low-carbon.csv?v=1&csvType=full&useColumnShortNames=true';
const CODES = 'https://cdn.jsdelivr.net/npm/i18n-iso-countries@7.11.0/codes.json';

/* entity,code,year,value — the newest year per ISO-3 code */
export function latest(csv) {
  const out = {};
  for (const line of csv.split(/\r?\n/).slice(1)) {
    const m = /^(?:"[^"]*"|[^,]*),([A-Z]{3}),(\d{4}),([-\d.]+)$/.exec(line.trim());
    if (!m) continue;
    const [, code, year, v] = m;
    if (!out[code] || +year > out[code].year) out[code] = { year: +year, v: +v };
  }
  return out;
}

if (process.argv[1] && process.argv[1].endsWith('grid-mix.mjs')) {
  const get = async u => { const r = await fetch(u, { headers: UA, redirect: 'follow' }); if (!r.ok) throw new Error(u + ' ' + r.status); return r.text(); };
  const [ci, lc, codes] = await Promise.all([get(CI), get(LC), get(CODES)]);
  const a2 = Object.fromEntries(JSON.parse(codes).map(([two, three]) => [three, two]));
  const cI = latest(ci), cL = latest(lc), out = {};
  for (const code of new Set([...Object.keys(cI), ...Object.keys(cL)])) {
    const cc = a2[code] || (code === 'OWID_KOS' ? 'XK' : '');
    if (!cc) continue;
    out[cc] = {
      ...(cI[code] ? { co2: Math.round(cI[code].v) } : {}),
      ...(cL[code] ? { lowc: Math.round(cL[code].v * 10) / 10 } : {}),
      year: Math.max(cI[code] ? cI[code].year : 0, cL[code] ? cL[code].year : 0),
    };
  }
  const src = `/* Generated by scripts/grid-mix.mjs on ${new Date().toISOString().slice(0, 10)} — do not edit by hand.
   Electricity by country, latest year: lifecycle carbon intensity (g CO2e/kWh)
   and low-carbon share (%, renewables + nuclear). Ember via Our World in Data, CC BY 4.0. */
export const GRID = ${JSON.stringify(out)};
`;
  console.log(Object.keys(out).length, 'countries; e.g.', ['US', 'DE', 'FR', 'NO', 'CN', 'JP', 'IN', 'PL'].map(c => c + ' ' + JSON.stringify(out[c])).join(' '));
  if (process.argv.includes('--write')) { writeFileSync(OUT, src); console.log('wrote', OUT.pathname); }
}
