#!/usr/bin/env node
/* Builds src/pumpseed.mjs: the established pump.fun coins the map keeps
   whether or not they are trending today.

   Jupiter's verified list (`/tokens/v2/tag?query=verified`) is ~5 MB, too
   much for a free-plan Worker request to parse in its 10 ms of CPU, so it is
   read here, offline, and only the mints are committed. At runtime the map
   asks Jupiter about these mints in one batched search call.

     node scripts/pumpseed.mjs           print what would be written
     node scripts/pumpseed.mjs --write   write src/pumpseed.mjs

   Re-run when the top of pump.fun turns over. */
import { writeFileSync } from 'node:fs';

const MIN_MCAP = 500_000;
const MIN_LIQ = 50_000;
const KEEP = 100;

const r = await fetch('https://lite-api.jup.ag/tokens/v2/tag?query=verified', {
  headers: { accept: 'application/json', 'user-agent': 'pumpbubble.fun/1.0 (+https://pumpbubble.fun)' },
});
if (!r.ok) { console.error('jupiter', r.status); process.exit(1); }
const all = await r.json();
const rows = all
  .filter(t => t && t.launchpad === 'pump.fun' && t.graduatedPool && /^[1-9A-HJ-NP-Za-km-z]{32,44}$/.test(t.id))
  .filter(t => +t.mcap >= MIN_MCAP && +t.liquidity >= MIN_LIQ)
  .sort((a, b) => b.mcap - a.mcap)
  .slice(0, KEEP);

const day = new Date().toISOString().slice(0, 10);
const body = `/* Generated by scripts/pumpseed.mjs on ${day} — do not edit by hand.
   The established pump.fun coins (Jupiter-verified, graduated, market cap
   ≥ $${MIN_MCAP / 1e3}K, liquidity ≥ $${MIN_LIQ / 1e3}K), largest first, so the
   map keeps them when they are not trending. Symbols are for reading only;
   the map takes every name and number from the live lookup. */
export const PUMP_SEED = [
${rows.map(t => `  '${t.id}', // ${String(t.symbol).replace(/[^\w.$-]/g, '').slice(0, 16)}`).join('\n')}
];
`;
console.log(rows.length + ' mints; largest ' + rows.slice(0, 5).map(t => t.symbol).join(', '));
if (process.argv.includes('--write')) { writeFileSync(new URL('../src/pumpseed.mjs', import.meta.url), body); console.log('wrote src/pumpseed.mjs'); }
