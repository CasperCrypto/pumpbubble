/* Rebuild the ticker -> CoinGecko id map that src/cryptowin.mjs feeds to
   DefiLlama.

     node scripts/cgmap.mjs           report only
     node scripts/cgmap.mjs --write   update src/cgmap.mjs

   Run from a laptop, not a Worker: CoinGecko's list endpoint rate-limits
   Cloudflare's shared egress, which is the whole reason the map is a committed
   file rather than something fetched at runtime.

   Matching by ticker alone is not safe — fifteen thousand coins share a few
   thousand tickers, and picking the wrong one returns a real price for the
   wrong asset, which is invisible on a map. So every candidate is verified:
   DefiLlama's current price for that id has to agree with CoinPaprika's price
   for the coin we are actually showing. Disagreement means the id is dropped,
   not guessed at. */

import { writeFileSync } from 'node:fs';

const WRITE = process.argv.includes('--write');
const TOL = 0.04;               /* 4%: venue spread, not a different asset. */
const CHUNK = 60;

const jget = async (u, ms = 25000) => {
  const r = await fetch(u, { headers: { accept: 'application/json' }, signal: AbortSignal.timeout(ms) });
  if (!r.ok) throw new Error(u.slice(0, 60) + ' -> ' + r.status);
  return r.json();
};

const norm = s => String(s || '').toLowerCase().replace(/[^a-z0-9]/g, '');

console.log('\n  fetching majors, coingecko list...');
const [feed, list] = await Promise.all([
  jget('https://pumpbubble.fun/api/tokens?source=majors'),
  jget('https://api.coingecko.com/api/v3/coins/list'),
]);

const majors = (feed.tokens || []).filter(t => t.sym && t.price > 0);
console.log('  majors ' + majors.length + ' · coingecko ' + list.length);

/* Candidate ids per ticker, best-guess first: an exact name match is far more
   likely right than an arbitrary coin sharing the ticker. */
const bySym = new Map();
for (const c of list) {
  const k = norm(c.symbol);
  if (!k) continue;
  if (!bySym.has(k)) bySym.set(k, []);
  bySym.get(k).push(c);
}

const wanted = [];
for (const t of majors) {
  const cands = (bySym.get(norm(t.sym)) || []).slice();
  if (!cands.length) continue;
  cands.sort((a, b) => (norm(b.name) === norm(t.name)) - (norm(a.name) === norm(t.name)));
  /* Three is plenty: beyond that the ticker is too contested to trust. */
  for (const c of cands.slice(0, 3)) wanted.push({ sym: t.sym, price: t.price, id: c.id, name: c.name });
}

console.log('  verifying ' + wanted.length + ' candidates by price...');
const ids = [...new Set(wanted.map(w => w.id))];
const price = new Map();
for (let i = 0; i < ids.length; i += CHUNK) {
  const part = ids.slice(i, i + CHUNK).map(x => 'coingecko:' + x).join(',');
  try {
    const j = await jget('https://coins.llama.fi/prices/current/' + part, 20000);
    for (const [k, v] of Object.entries(j.coins || {})) {
      if (v && v.price > 0) price.set(k.replace(/^coingecko:/, ''), v.price);
    }
  } catch (e) { console.log('    chunk failed: ' + e.message); }
}

const map = {}, rejected = [];
for (const w of wanted) {
  if (map[w.sym]) continue;                    /* first verified wins */
  const p = price.get(w.id);
  if (!p) continue;
  const off = Math.abs(p - w.price) / w.price;
  if (off <= TOL) map[w.sym] = w.id;
  else rejected.push(w.sym + ' != ' + w.id + ' (' + (off * 100).toFixed(0) + '% off)');
}

const hit = Object.keys(map).length;
console.log('\n  mapped   ' + hit + '/' + majors.length + '  (' + Math.round(hit / majors.length * 100) + '%)');
console.log('  rejected ' + rejected.length + ' wrong-coin matches');
for (const r of rejected.slice(0, 8)) console.log('    ' + r);
const missing = majors.filter(t => !map[t.sym]).map(t => t.sym);
console.log('  unmapped: ' + missing.slice(0, 24).join(' '));

if (WRITE) {
  const head = [
    '/* Generated by scripts/cgmap.mjs - do not edit by hand.',
    '   Ticker -> CoinGecko id, every entry verified against a live price.',
    '   Regenerate when the top 250 changes: node scripts/cgmap.mjs --write */',
    '',
  ].join(String.fromCharCode(10));
  writeFileSync('src/cgmap.mjs', head + 'export default ' + JSON.stringify(map) + ';' + String.fromCharCode(10));
  console.log('  wrote src/cgmap.mjs (' + hit + ' entries)');
} else {
  console.log('  dry run. add --write to save.');
}
